import type { Preview } from '@storybook/web-components-vite';
import { setCustomElementsManifest } from '@storybook/web-components-vite';
import customElements from '../custom-elements.json';
import { colorThemes, materials, structures } from '../src/configs/themes';

/* Controls and the props/events/slots/parts tables come from the manifest
   generated by `pnpm cem`, not from the source at runtime.

   Storybook keys every row of the args table by its bare name, whatever its
   category, and a later category replaces an earlier one: a slot or part
   named like a property took that property's row and its control, as with
   each field's `label`, `hint` and `error`. Parts are listed as a consumer
   writes them, `::part(label)`. A slot keeps its bare name, which stories
   use as an arg for the slot's content, unless a property or attribute
   shares it: it is then listed as `slot="label"`. */
type Named = { name: string; kind?: string };
type Declaration = {
    members?: Named[];
    attributes?: Named[];
    slots?: Named[];
    cssParts?: Named[];
};
const manifest = structuredClone(customElements) as unknown as {
    modules: { declarations?: Declaration[] }[];
};
for (const declaration of manifest.modules.flatMap(
    (module) => module.declarations ?? [],
)) {
    const api = new Set(
        [
            ...(declaration.members ?? []).filter((m) => m.kind !== 'method'),
            ...(declaration.attributes ?? []),
        ].map((item) => item.name),
    );
    for (const slot of declaration.slots ?? [])
        if (api.has(slot.name)) slot.name = `slot="${slot.name}"`;
    for (const part of declaration.cssParts ?? [])
        part.name = `::part(${part.name})`;
}
setCustomElementsManifest(manifest);

/* The library themes off three independent <html> attributes. addon-themes
   only tracks one axis, so drive all three from our own globals. */
const AXES = [
    { global: 'theme', attribute: 'data-theme', values: colorThemes },
    { global: 'structure', attribute: 'data-structure', values: structures },
    { global: 'material', attribute: 'data-material', values: materials },
] as const;

type Scheme = 'system' | 'light' | 'dark';

/* The themes switch to dark only through `@media (prefers-color-scheme:
   dark)`, and a page cannot emulate that query for itself. To preview either
   scheme whatever the system's, the scheme toolbar rewrites those media rules
   in the theme sheets: `all` forces dark, `not all` forces light, and the
   system choice restores each rule's own text. */
const DARK = /prefers-color-scheme:\s*dark/;
const originalMedia = new WeakMap<CSSMediaRule, string>();

function applyScheme(scheme: Scheme) {
    const visit = (rules: CSSRuleList) => {
        for (const rule of rules) {
            if (!(rule instanceof CSSMediaRule)) continue;
            const original = originalMedia.get(rule) ?? rule.media.mediaText;
            if (DARK.test(original)) {
                originalMedia.set(rule, original);
                rule.media.mediaText =
                    scheme === 'dark'
                        ? 'all'
                        : scheme === 'light'
                          ? 'not all'
                          : original;
            }
            visit(rule.cssRules);
        }
    };
    for (const sheet of document.styleSheets) {
        if (!/\/css\/(themes\/|base\.css)/.test(sheet.href ?? '')) continue;
        visit(sheet.cssRules);
    }
    // Native controls and scrollbars follow the same scheme.
    document.documentElement.style.colorScheme =
        scheme === 'system' ? '' : scheme;
}

const preview: Preview = {
    parameters: {
        controls: { matchers: { color: /(background|color)$/i } },
        options: { storySort: { order: ['Overview', 'Components', 'Charts'] } },
    },
    globalTypes: {
        ...Object.fromEntries(
            AXES.map(({ global, values }) => [
                global,
                {
                    description: `Active ${global}`,
                    toolbar: {
                        title: global,
                        items: values as unknown as string[],
                        dynamicTitle: true,
                    },
                },
            ]),
        ),
        scheme: {
            description: 'Light or dark, or the system setting',
            toolbar: {
                title: 'scheme',
                icon: 'mirror',
                items: [
                    { value: 'system', title: 'system' },
                    { value: 'light', title: 'light', icon: 'sun' },
                    { value: 'dark', title: 'dark', icon: 'moon' },
                ],
                dynamicTitle: true,
            },
        },
    },
    initialGlobals: {
        theme: 'default',
        structure: 'default',
        material: 'solid',
        scheme: 'system',
    },
    decorators: [
        (story, context) => {
            for (const { global, attribute } of AXES) {
                const value = context.globals[global];
                if (value)
                    document.documentElement.setAttribute(attribute, value);
            }
            applyScheme(context.globals.scheme ?? 'system');
            return story();
        },
    ],
};

export default preview;
